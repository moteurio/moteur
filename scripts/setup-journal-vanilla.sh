#!/usr/bin/env bash
# Build Moteur Journal demo, create a starter API key, write vanilla config.local.js
set -euo pipefail

ROOT="$(cd "$(dirname "$0")/.." && pwd)"
STARTERS="${STARTERS_DIR:-$(dirname "$ROOT")/moteur-starters}"
VANILLA="$STARTERS/packages/vanilla"
API_URL="${MOTEUR_API_URL:-http://localhost:3000}"
DEMO_PASSWORD="${MOTEUR_DEMO_PASSWORD:-demo123}"
SERVE_PORT="${STARTER_PORT:-8080}"

cd "$ROOT"

if [[ ! -d "$VANILLA/js" ]]; then
  echo "Vanilla starter not found at $VANILLA"
  echo "Set STARTERS_DIR or clone moteur-starters next to moteur."
  exit 1
fi

echo "==> Installing & building moteur (skip if already done)..."
if [[ ! -d node_modules ]]; then pnpm install; fi
if [[ ! -d data/projects/demo ]]; then
  pnpm demo:build journal --force --password "$DEMO_PASSWORD" --asset-base-url "$API_URL"
else
  echo "    data/projects/demo exists — skip demo:build (use --force rebuild manually if needed)"
fi

export CORS_ORIGINS="${CORS_ORIGINS:-http://localhost:3000,http://localhost:5173,http://localhost:5181,http://localhost:${SERVE_PORT}}"
export STATIC_ASSETS_BASE_URL="${STATIC_ASSETS_BASE_URL:-$API_URL}"

if ! curl -sf "$API_URL/health" >/dev/null 2>&1; then
  echo "==> Starting API on $API_URL (background)..."
  pnpm server:dev >>"$ROOT/.starter-api.log" 2>&1 &
  API_PID=$!
  echo "$API_PID" >"$ROOT/.starter-api.pid"
  for _ in $(seq 1 60); do
    curl -sf "$API_URL/health" >/dev/null 2>&1 && break
    sleep 1
  done
  if ! curl -sf "$API_URL/health" >/dev/null 2>&1; then
    echo "API did not become ready. See .starter-api.log"
    exit 1
  fi
else
  echo "==> API already up at $API_URL"
fi

echo "==> Creating API key..."
KEY_OUT=$(pnpm exec tsx --tsconfig tsconfig.server-dev.json scripts/create-demo-api-key.ts \
  --api-url "$API_URL" --password "$DEMO_PASSWORD")
eval "$(echo "$KEY_OUT" | grep '^MOTEUR_' | sed 's/^/export /')"

CONFIG="$VANILLA/js/config.local.js"
cat >"$CONFIG" <<EOF
// Generated by moteur/scripts/setup-journal-vanilla.sh — safe to regenerate.
window.MOTEUR_API_URL = '$MOTEUR_API_URL';
window.MOTEUR_PROJECT_ID = '$MOTEUR_PROJECT_ID';
window.MOTEUR_CHANNEL = '$MOTEUR_CHANNEL';
window.MOTEUR_API_KEY = '$MOTEUR_API_KEY';
EOF
echo "==> Wrote $CONFIG"

echo ""
echo "Done. In another terminal:"
echo "  cd \"$VANILLA\""
echo "  node serve-local.mjs $SERVE_PORT"
echo ""
echo "Open http://localhost:$SERVE_PORT/fr/"
echo "API: $API_URL  |  Studio sign-in: louise@moteur-journal.test / $DEMO_PASSWORD"
echo "CORS_ORIGINS for this run: $CORS_ORIGINS"
