#!/usr/bin/env bash
# One-shot: Journal demo + API key + optional Next starter .env.local
set -euo pipefail

ROOT="$(cd "$(dirname "$0")/.." && pwd)"
STARTERS="${STARTERS_ROOT:-$(dirname "$ROOT")/moteur-starters}"
NEXT="$STARTERS/packages/next"
API_URL="${MOTEUR_API_URL:-http://localhost:3000}"
DEMO_PW="${MOTEUR_DEMO_PASSWORD:-demo123}"
LOG="$ROOT/.setup-journal-next.log"

exec > >(tee -a "$LOG") 2>&1

echo "== moteur root: $ROOT"
echo "== starters: $STARTERS"
echo "== log: $LOG"

cd "$ROOT"

if [[ ! -d node_modules ]]; then
  echo "== pnpm install"
  pnpm install
fi

echo "== pnpm build"
pnpm build

echo "== demo:build journal"
pnpm demo:build journal --force --password "$DEMO_PW" --asset-base-url "$API_URL"

USERS_FILE="$ROOT/data/users.json"
if [[ ! -f "$USERS_FILE" ]]; then
  echo "ERROR: expected $USERS_FILE after demo build"
  exit 1
fi

echo "== demo users (first 5 emails)"
node -e "
const u=require('$USERS_FILE');
const emails=(u.users||u||[]).map(x=>x.email).filter(Boolean);
console.log(emails.slice(0,5).join('\n') || JSON.stringify(u,null,2).slice(0,500));
"

if [[ ! -d "$STARTERS/.git" ]]; then
  echo "== clone moteur-starters"
  git clone https://github.com/moteurio/moteur-starters.git "$STARTERS"
else
  echo "== fetch latest moteur-starters"
  (cd "$STARTERS" && git fetch origin && git pull --ff-only || true)
fi

if [[ ! -f "$NEXT/package.json" ]]; then
  echo "ERROR: Next starter missing at $NEXT (only placeholder README in partial clone?)"
  echo "Try: rm -rf '$STARTERS' && git clone https://github.com/moteurio/moteur-starters.git '$STARTERS'"
  exit 1
fi

echo "== create API key (project demo, collection public)"
KEY_OUT="$ROOT/.demo-public-api-key.txt"
pnpm exec tsx --tsconfig "$ROOT/tsconfig.server-dev.json" "$ROOT/scripts/create-demo-api-key.ts" \
  --api-url "$API_URL" \
  --project demo \
  --collection public \
  --email "louise@moteur-journal.test" \
  --password "$DEMO_PW" \
  | tee "$KEY_OUT"

RAW_KEY="$(grep -E '^MOTEUR_API_KEY=' "$KEY_OUT" | cut -d= -f2- || true)"

ENV_LOCAL="$NEXT/.env.local"
cat > "$ENV_LOCAL" <<EOF
# Generated by scripts/setup-journal-next.sh
MOTEUR_API_URL=$API_URL
MOTEUR_API_KEY=${RAW_KEY:-REPLACE_ME}
MOTEUR_PROJECT_ID=demo
MOTEUR_COLLECTION_ID=public
EOF
echo "== wrote $ENV_LOCAL"

if ! curl -sf "$API_URL/health" >/dev/null 2>&1 && ! curl -sf "$API_URL/api/health" >/dev/null 2>&1; then
  echo "== starting API on :3000 (background)"
  cd "$ROOT"
  nohup pnpm server:dev > "$ROOT/.api-dev.log" 2>&1 &
  echo $! > "$ROOT/.api-dev.pid"
  sleep 3
fi

echo "== next starter: pnpm install"
cd "$NEXT"
pnpm install

echo "== next starter: pnpm dev (background on :3001 if 3000 taken by API)"
PORT=3001 nohup pnpm dev > "$NEXT/.next-dev.log" 2>&1 &
echo $! > "$NEXT/.next-dev.pid"

echo ""
echo "DONE"
echo "  API:        $API_URL"
echo "  Studio login: louise@moteur-journal.test / $DEMO_PW"
echo "  Next env:   $ENV_LOCAL"
echo "  API key:    see $KEY_OUT"
echo "  Open Next:  http://localhost:3001 (or check $NEXT/.next-dev.log for port)"
