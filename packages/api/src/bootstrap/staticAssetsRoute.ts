import fs from 'fs';
import path from 'path';
import type { Express, Request, Response } from 'express';
import { storageConfig } from '@moteurio/core';
import {
    getResizedImage,
    parseResizeRequest,
    resizeContentType,
    ResizeNotFound
} from '@moteurio/core/assets/resize.js';

/** Extensions that browsers display or play inline. Every other file is served as a download and never rendered. */
const INLINE = new Set([
    '.jpg',
    '.jpeg',
    '.png',
    '.gif',
    '.webp',
    '.avif',
    '.mp4',
    '.m4v',
    '.mov',
    '.webm',
    '.mp3',
    '.m4a',
    '.aac',
    '.wav',
    '.ogg',
    '.oga',
    '.weba',
    '.flac',
    '.pdf',
    '.glb',
    '.gltf',
    '.usdz'
]);

function assertSafeSegment(value: string, _label: string): boolean {
    if (!value || value.includes('/') || value.includes('\\') || value === '.' || value === '..') {
        return false;
    }
    return true;
}

/**
 * Serves assets stored on local disk. The URL layout must match the URLs generated by LocalAdapter.
 */
export function mountStaticAssets(app: Express, basePath: string): void {
    const prefix = `${basePath}/static/assets/:projectId/:variantKey/:filename`;
    app.get(prefix, (req: Request, res: Response): void => {
        const { projectId, variantKey, filename } = req.params as Record<string, string>;
        if (
            !assertSafeSegment(projectId, 'projectId') ||
            !assertSafeSegment(variantKey, 'variantKey') ||
            !assertSafeSegment(filename, 'filename')
        ) {
            res.status(400).end();
            return;
        }

        const projectsDir = path.resolve(storageConfig.projectsDir);
        const projectRoot = path.resolve(projectsDir, projectId);
        const relProject = path.relative(projectsDir, projectRoot);
        if (relProject.startsWith('..') || path.isAbsolute(relProject)) {
            res.status(400).end();
            return;
        }

        const filePath = path.resolve(projectRoot, 'assets', variantKey, filename);
        const relFile = path.relative(projectRoot, filePath);
        if (relFile.startsWith('..') || path.isAbsolute(relFile)) {
            res.status(400).end();
            return;
        }

        if (!fs.existsSync(filePath) || !fs.statSync(filePath).isFile()) {
            res.status(404).end();
            return;
        }
        // Sites and admin clients on other origins embed media, but the global security headers
        // (Helmet) would otherwise restrict it to the same origin.
        res.setHeader('Cross-Origin-Resource-Policy', 'cross-origin');
        // Files are user uploads. Disable content sniffing so browsers use the declared type, and
        // serve anything that is not media as a download so uploaded content never runs on the API's origin.
        res.setHeader('X-Content-Type-Options', 'nosniff');
        if (!INLINE.has(path.extname(filename).toLowerCase())) {
            res.setHeader('Content-Security-Policy', "default-src 'none'; sandbox");
            res.attachment(filename);
        }
        // Originals never change, and rebuilt copies get a new `?v=`, so both can be cached indefinitely.
        // A copy requested without a version (an old link) may change, so cache it for an hour only.
        const immutable = variantKey === 'original' || typeof req.query.v === 'string';
        res.setHeader(
            'Cache-Control',
            immutable ? 'public, max-age=31536000, immutable' : 'public, max-age=3600'
        );
        // The path is validated above; the data root itself may sit under a dot-directory
        // (e.g. ~/.moteur), which send() would otherwise refuse with a 404.
        res.sendFile(filePath, { dotfiles: 'allow' });
    });
}

/**
 * Serves images at any size, regardless of the project's storage (`asset.resizeUrl` + `&w=640`,
 * optionally `&ar=1:1` and `&fmt=avif`). Each size is generated once and stored with the asset's other files.
 */
export function mountResizedImages(app: Express, basePath: string): void {
    app.get(
        `${basePath}/static/resize/:projectId/:assetId`,
        async (req: Request, res: Response): Promise<void> => {
            const { projectId, assetId } = req.params as Record<string, string>;
            if (
                !assertSafeSegment(projectId, 'projectId') ||
                !assertSafeSegment(assetId, 'assetId')
            ) {
                res.status(400).end();
                return;
            }
            let request;
            try {
                request = parseResizeRequest(req.query as Record<string, unknown>);
            } catch (err) {
                res.status(400).json({ error: (err as Error).message });
                return;
            }
            try {
                const { buffer, format, etag } = await getResizedImage(projectId, assetId, request);
                res.setHeader('Cross-Origin-Resource-Policy', 'cross-origin');
                res.setHeader('Content-Type', resizeContentType(format));
                // `v` changes when the crops change. Without it the response may change later, so cache it for an hour only.
                res.setHeader(
                    'Cache-Control',
                    typeof req.query.v === 'string'
                        ? 'public, max-age=31536000, immutable'
                        : 'public, max-age=3600'
                );
                // A browser or CDN that already has the image revalidates with the ETag, so no body is needed.
                res.setHeader('ETag', etag);
                if (req.fresh) {
                    res.status(304).end();
                    return;
                }
                // Set explicitly because usageLogging uses it to count image traffic.
                res.setHeader('Content-Length', buffer.length);
                res.end(buffer);
            } catch (err) {
                if (err instanceof ResizeNotFound) {
                    res.status(404).end();
                    return;
                }
                if ((err as { code?: string }).code === 'WORK_CAPACITY') {
                    // Too many resizes are running at once. This is an expected response, not an error to log.
                    res.setHeader('Retry-After', '2');
                    res.setHeader('Cache-Control', 'no-store');
                    res.status(503).json({ error: (err as Error).message });
                    return;
                }
                console.error('[moteur] resize failed', projectId, assetId, err);
                res.status(500).json({ error: 'The image could not be resized.' });
            }
        }
    );
}
